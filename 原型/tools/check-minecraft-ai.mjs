stale.start('page-test');const work=stale.tick();bridges[1].rules.states.get('月月').revision++;
deliver({action:'wait',text:'过期'});await work;assert.equal(stale.ready.length,0,'搭档受伤使旧生成失效');
now+=16000;await stale.tick();assert.equal(stale.enabled,false);
