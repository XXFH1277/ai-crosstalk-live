import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { createRequire } from 'node:module';
import { attachCPM, modelPacket } from '../minecraft/cpm.mjs';
const require=createRequire(new URL('../minecraft/package.json',import.meta.url));
const nbt=require('prismarine-nbt');
const input=Buffer.from([1,2,3,4,255]);
const decoded=nbt.parseUncompressed(modelPacket(input));
assert.deepEqual(Buffer.from(decoded.value.data.value),input);
assert.throws(()=>modelPacket(Buffer.alloc(31*1024)));
const bot=new EventEmitter();bot._client=new EventEmitter();
const sent=[];bot._client.write=(name,p)=>sent.push({name,...p});
attachCPM(bot,'ShenshenBot');
bot._client.emit('custom_payload',{channel:'cpm_net:get_skin'});
assert.equal(sent.length,0,'入服前不发送模型');
bot.emit('spawn');
assert.equal(sent[0].channel,'minecraft:register');
assert.equal(sent[1].channel,'cpm_net:hello');
assert.equal(sent[2].channel,'cpm_net:set_skin');
assert.ok(nbt.parseUncompressed(sent[2].data).value.data.value.length>20000);
for(let i=0;i<10;i++)bot._client.emit('custom_payload',{channel:'cpm_net:get_skin'});
assert.equal(sent.filter(p=>p.channel==='cpm_net:set_skin').length,3,'服务器重复请求有界');
bot.emit('end');const count=sent.length;
bot._client.emit('custom_payload',{channel:'cpm_net:get_skin'});
assert.equal(sent.length,count,'断连后不发送');
console.log('CPM 协议及连接生命周期检查通过');
