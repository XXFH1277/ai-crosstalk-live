const ai=new GameAI(options);ai.start('page-test');
await ai.tick();assert.equal(ai.ready.length,1);assert.equal(ai.pending,null);assert.equal(moves.length,0,'预生成不得提前执行动作');
now+=101;await ai.tick();assert.equal(ai.ready.length,2);
assert.equal(contexts[1].at(-1).who,'深深','月月预生成时能接住待播的上一句');
assert.equal(contexts[1].at(-1).status,'待播放');
now+=101;await ai.tick();assert.equal(ai.pending.who,'深深');assert.equal(moves[0],'深深');assert.equal(ai.history.length,0);
assert.equal(ai.ready.length,2,'当前句播放时继续补充缓冲');
const first=ai.pending.id;assert.equal(ai.acknowledge('wrong-page',first,'played'),false);
ai.acknowledge('page-test',first,'played');assert.equal(ai.history.length,1);
now+=401;await ai.tick();assert.equal(ai.pending.who,'月月');
ai.invalidate();assert.equal(ai.pending,null);assert.equal(ai.ready.length,0);assert.equal(ai.history.length,1);
ai.stop();assert.ok(bridges.every(b=>b.stopped));
let release;const slow=new GameAI({...options,voice:()=>new Promise(r=>{release=r;})});
slow.start('page-test');const running=slow.tick();await Promise.resolve();await Promise.resolve();assert.ok(release);
slow.stop();release({url:'/audio/old.wav',seconds:1});await running;assert.equal(slow.ready.length,0,'暂停后迟到配音不得重新入队');
