import assert from 'node:assert/strict';
import {SurvivalGoals,woodUnits,stoneUnits} from '../minecraft/goals.mjs';
import {GameTasks,parseTask} from '../minecraft/tasks.mjs';
import {inActivityArea,explorationChoices,chooseActivity} from '../minecraft/autonomy.mjs';
import {taskOptions} from '../minecraft/task-world.mjs';

globalThis.fetch=()=>{throw Error('离线检查不得联网');};
const goals=new SurvivalGoals(),gear=[{name:'stone_pickaxe',count:1},{name:'stone_sword',count:1}];
const world=['深深','月月'].map(who=>({who,status:'已入服',health:20,food:20,position:{x:0,y:64,z:0},inventory:[]}));
assert.equal(goals.choose(world[0],world,[],{}).stage,'gear','空背包首先准备工具，不空手一直挖矿');
world.forEach(w=>w.inventory=[...gear]);
assert.equal(goals.choose(world[0],world,[],{}).stage,'wood');
assert.equal(goals.choose(world[1],world,[],{}).stage,'mine','两人按共同缺口分工');
world[0].food=3;assert.equal(goals.snapshot(world).phase,'safety');assert.match(goals.choose(world[0],world,[],{}).id,/safety/,'饥饿应成为优先条件，不继续追求建材');world[0].food=20;
assert.equal(woodUnits([{name:'oak_log',count:2},{name:'oak_planks',count:3}]),11);
assert.equal(stoneUnits([{name:'coal',count:64},{name:'raw_iron',count:64},{name:'cobblestone',count:2}]),2,'煤铁不能冒充据点圆石');
world[0].inventory.push({name:'oak_log',count:24});
assert.equal(goals.choose(world[0],world,[],{}).stage,'mine','木料够了帮助补另一项，不按死循环继续砍树');
world[1].inventory.push({name:'cobblestone',count:31});
const reserved=[{who:'月月',mode:'auto',status:'执行中',stage:'mine',goal:{resourceStage:'mine'},quota:1,count:0}];
assert.equal(goals.choose(world[0],world,reserved,{}).id,'waiting-delivery','同伴已领取最后一块，不重复安排');
assert.equal(goals.assess(world).stocked,false,'计划中的那一块不算库存');
world[1].inventory.at(-1).count=32;
const ready=goals.snapshot(world);
assert.equal(ready.phase,'shelter');assert.equal(ready.milestones[1].status,'已核实');
assert.match(ready.milestones[2].status,/待接入/,'材料足够也不能宣称房屋已建成');
assert.equal(goals.choose(world[0],world,[],{}).stage,'blocked');
world[0].inventory=gear.slice();
assert.equal(goals.snapshot(world).phase,'supplies','材料消耗或遗失，目标应重新出现');
world[0].inventory=[];assert.equal(goals.snapshot(world).phase,'tools','丢失装备应重新走前置条件');
assert.equal(parseTask('两人继续生存计划','player').mode,'auto');
assert.equal(inActivityArea({kind:'craft'}, {anchor:{x:0,y:64,z:0}},{}),true,'背包合成不需要地面坐标');
assert.equal(inActivityArea({kind:'craft',table:{x:40,y:64,z:0}}, {anchor:{x:0,y:64,z:0}},{}),false);
const searchJob={anchor:{x:0,y:64,z:0},round:0,visited:[],searchTargets:[{x:-10,y:64,z:0}],goal:{id:'supplies:wood'}};
const directions={position:{x:0,y:64,z:0},choices:[{type:'walk',position:{x:3,y:64,z:0}},{type:'walk',position:{x:-3,y:64,z:0}}]};
assert.equal(explorationChoices(directions,searchJob)[0].position.x,-3,'有已发现的资源时朝资源靠近，不继续按方向轮换');
chooseActivity({...directions,food:20},searchJob,1000,{id:'supplies:stone',stage:'mine',quota:2});assert.deepEqual(searchJob.searchTargets,[],'换子目标不能沿用上一类资源的位置');

let now=1000,resources=false,executed=[];
const settle=()=>new Promise(r=>setImmediate(r));
const bridges=world.map((w,i)=>({who:w.who,session:1,state:{status:'已入服',position:{x:i*2,y:64,z:0},players:[]},items:gear.slice(),stop(){this.state.target=null;},follow(){throw Error('自主目标不能偷偷跟随');}}));
const observe=b=>({...b.state,who:b.who,health:20,food:20,inventory:b.items,choices:[{id:'wait',type:'wait'},{id:'walk',type:'walk',position:{x:b.state.position.x+3,y:64,z:0}}]});
const tasks=new GameTasks({bridges,goals,observe,now:()=>now,publish(){},options:(b,j)=>({choices:resources?[{key:b.who,kind:j.stage==='gear'?'craft':'dig',position:b.state.position,label:'执行本阶段动作'}]:[]}),execute:async(b,c)=>{executed.push(c.kind);if(c.kind==='walk')b.state.position={...c.position};if(c.kind==='craft')b.items=gear.slice();return {text:'动作结束'};}});
tasks.startDefault('player');tasks.tick();await settle();
const ids=tasks.snapshot().map(j=>j.goal.id);
now+=1501;tasks.tick();await settle();assert.ok(executed.includes('walk'),'缺资源时换地方查找');
assert.deepEqual(tasks.snapshot().map(j=>j.goal.id),ids,'换地方不遗忘原来的子目标');
for(let i=0;i<4;i++){now+=1600;tasks.tick();await settle();}
assert.deepEqual(tasks.snapshot().map(j=>j.goal.id),ids);
tasks.stop();bridges[0].items=[];resources=true;tasks.startDefault('player');tasks.tick();await settle();
assert.ok(executed.includes('craft'),'自动规划的工具前置实际进入任务执行器');
now+=1500;tasks.tick();assert.notEqual(tasks.snapshot()[0].status,'已完成','石工具完成只结束子目标，不结束长期路线');
tasks.assign(parseTask('深深跟着我','player'));assert.equal(tasks.snapshot().find(j=>j.who==='深深').mode,'follow','玩家明确指令覆盖自主计划');
tasks.stop();for(let i=0;i<3;i++){now+=6000;tasks.tick();}assert.equal(tasks.snapshot().length,0,'暂停后长期目标不能擅自重启动作');

const matches=[];
const bot={entity:{position:{x:0,y:64,z:0}},entities:{},inventory:{items:()=>gear},findBlocks:({matching})=>{for(const name of ['stone','coal_ore','iron_ore','deepslate'])if(matching({name}))matches.push(name);return [];}};
assert.equal(taskOptions({bot},{stage:'mine',resource:'cobblestone'}).choices.length,0);
assert.deepEqual(matches,['stone'],'执行器也必须按指定建材筛选方块');
console.log('PASS 生存目标：工具前置、共同缺口、分工与预留、保留目标找资源、真实库存验收、丢失重规划、能力缺口、手动优先及暂停');
